  currentTourStep: number;
  tourHighlightedNodeIds: string[];

  persona: Persona;

  diffMode: boolean;
  changedNodeIds: Set<string>;
  affectedNodeIds: Set<string>;

  focusNodeId: string | null;

  nodeHistory: string[];

  filters: FilterState;
  filterPanelOpen: boolean;
  pathFinderOpen: boolean;
